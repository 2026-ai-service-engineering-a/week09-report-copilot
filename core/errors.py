"""코어가 바깥에 알리는 실패의 종류.

**코어는 HTTP도 AG-UI도 모른다.** 상태 코드로 옮기는 일은 문(api/errors.py)이
하고, 이벤트로 옮기는 일은 AG-UI 엔드포인트가 한다. 코어는 "무엇이
실패했는가"만 말한다. 8주차 `core/errors.py`와 같은 자리이고, 9주차에 둘이
늘었다.
"""


class CoreError(Exception):
    """이 저장소가 스스로 만들어 던지는 실패의 뿌리."""


class UpstreamError(CoreError):
    """모델 쪽(상류)이 실패했다. 우리 잘못이 아니다 — 502로 옮겨진다."""


class UpstreamTimeout(CoreError):
    """모델 쪽이 제때 답하지 않았다 — 504로 옮겨진다."""


class BlockedQuery(CoreError):
    """하네스가 질의를 막았다.

    9주차에 새로 생긴 실패다. 모델이 질의를 짜는 제품이라 막을 일이 생긴다.
    사용자 잘못도 상류 장애도 아니므로 500이나 502가 아니라, **무엇이 막혔는지
    답으로 알린다** (교안 9장 1절).
    """


class UnknownMetric(CoreError):
    """지표 사전에 없는 용어다.

    조용히 넘어가면 모델이 지어낸다. 지어낸 지표로 만든 리포트는 형태가
    멀쩡해서 틀렸다는 것조차 알기 어렵다 (교안 10장 2절).
    """
